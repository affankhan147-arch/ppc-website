// Builds src/data/contentDates.ts: URL path -> first-published date (YYYY-MM-DD), taken from git history.
// Used for Article schema datePublished and the visible "Published" line. AI answer engines and Google
// weigh dated, attributed content; undated pages read as stale or anonymous. Re-run after adding content:
//   node scripts/gen-content-dates.mjs
import { execSync } from "node:child_process";
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { createJiti } from "jiti";

const jiti = createJiti(import.meta.url);
const git = (args) => {
  try {
    return execSync(`git ${args}`, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
};
const oldest = (out) => out.split(/\r?\n/).filter(Boolean).sort()[0] || "";
const esc = (s) => s.replace(/"/g, '\\"').replace(/`/g, "\\`").replace(/\$/g, "\\$");
const pickaxe = (needle, file) => oldest(git(`log -S "${esc(needle)}" --format=%as -- ${file}`));

const dates = {};

// 1) Data-driven blog posts (/blog/[postSlug]); generated slugs come from titles, so search title first.
const blog = await jiti.import("../src/data/blogPosts.ts");
const posts = new Map();
for (const v of Object.values(blog)) {
  if (Array.isArray(v)) v.forEach((p) => p && p.slug && p.title && posts.set(p.slug, p));
  else if (v && typeof v === "object" && v.slug && v.title) posts.set(v.slug, v);
}
for (const p of posts.values()) {
  const d = pickaxe(p.title, "src/data/blogPosts.ts") || pickaxe(`"${p.slug}"`, "src/data/blogPosts.ts");
  if (d) dates[`/blog/${p.slug}`] = d;
}

// 2) Problem pages (/problems/[problemSlug]).
const prob = await jiti.import("../src/data/problems.ts");
for (const v of Object.values(prob)) {
  if (!Array.isArray(v)) continue;
  for (const p of v) {
    if (!p || !p.slug) continue;
    const d = pickaxe(`slug: "${p.slug}"`, "src/data/problems.ts");
    if (d) dates[`/problems/${p.slug}`] = d;
  }
}

// 3) Literal folder pages under /blog, /guides and /tools: first commit that added page.tsx.
for (const section of ["blog", "guides", "tools"]) {
  const dir = `src/app/${section}`;
  if (!existsSync(dir)) continue;
  for (const name of readdirSync(dir, { withFileTypes: true })) {
    if (!name.isDirectory() || name.name.startsWith("[")) continue;
    const file = `${dir}/${name.name}/page.tsx`;
    if (!existsSync(file)) continue;
    const d = oldest(git(`log --diff-filter=A --format=%as -- "${file}"`));
    if (d) dates[`/${section}/${name.name}`] = d;
  }
}

const sorted = Object.fromEntries(Object.entries(dates).sort(([a], [b]) => a.localeCompare(b)));
const body =
  "// Generated by scripts/gen-content-dates.mjs from git history. Do not edit by hand.\n" +
  "export const contentPublished: Record<string, string> = " +
  JSON.stringify(sorted, null, 2) +
  ";\n";
writeFileSync("src/data/contentDates.ts", body);
console.log("dates:", Object.keys(sorted).length);
